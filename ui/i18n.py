# ------------------------------------------------------------------ languages
# code -> (English name, native name, flag)
LANGS: dict[str, tuple[str, str, str]] = {
    "en": ("English", "English", "gb"),
    "hi": ("Hindi", "हिन्दी", "in"),
    "es": ("Spanish", "Español", "es"),
    "fr": ("French", "Français", "fr"),
    "de": ("German", "Deutsch", "de"),
    "pt": ("Portuguese (BR)", "Português", "br"),
    "ja": ("Japanese", "日本語", "jp"),
    "zh": ("Chinese", "中文", "cn"),
}
DEFAULT_LANG = "en"


class I18n(QObject):
    changed = pyqtSignal()

    def __init__(self) -> None:
        super().__init__()
        self.lang = DEFAULT_LANG

    def set_language(self, code: str) -> None:
        if code not in LANGS:
            code = DEFAULT_LANG
        if code == self.lang:
            return
        self.lang = code
        self.changed.emit()

    def native_name(self, code: str | None = None) -> str:
        return LANGS.get(code or self.lang, LANGS[DEFAULT_LANG])[1]

    def flag_code(self, code: str | None = None) -> str:
        return LANGS.get(code or self.lang, LANGS[DEFAULT_LANG])[2]


i18n = I18n()


def tr(key: str, **kw) -> str:
    s = STRINGS.get(i18n.lang, {}).get(key) or STRINGS[DEFAULT_LANG].get(key) or key
    if kw:
        try:
            s = s.format(**kw)
        except Exception:  # noqa: BLE001
            pass
    return s


