"""Transfer Now 1.0.0.0 — light-weight i18n: 8 languages + drawn country flags.

``tr("nav.upload")`` returns the translated string for the current language,
falling back to English for anything not translated yet.  Flags are small SVGs
rendered through QSvgRenderer — no image assets needed.
"""
