def flag_svg(code: str, w: int, h: int) -> str:
    body = _FLAGS.get(code, _FLAGS["gb"])
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" '
            f'viewBox="0 0 60 40">{body}</svg>')


def flag_pixmap(code: str, w: int = 24, h: int = 16) -> QPixmap:
    """A country flag pixmap (rounded corners), rendered crisp for the screen."""
    from PyQt6.QtGui import QPainterPath
    from PyQt6.QtWidgets import QApplication
    dpr = 1.0
    app = QApplication.instance()
    if app is not None:
        try:
            screens = app.screens()
            dpr = max(1.0, float(screens[0].devicePixelRatio())) if screens else 1.0
        except Exception:  # noqa: BLE001
            pass
    pw, ph = int(w * dpr), int(h * dpr)
    renderer = QSvgRenderer(QByteArray(flag_svg(code, pw, ph).encode("utf-8")))
    pm = QPixmap(pw, ph)
    pm.fill(Qt.GlobalColor.transparent)
    p = QPainter(pm)
    p.setRenderHint(QPainter.RenderHint.Antialiasing, True)
    path = QPainterPath()
    path.addRoundedRect(QRectF(0, 0, pw, ph), 2.5 * dpr, 2.5 * dpr)
    p.setClipPath(path)
    renderer.render(p, QRectF(0, 0, pw, ph))
    p.end()
    pm.setDevicePixelRatio(dpr)
    return pm
