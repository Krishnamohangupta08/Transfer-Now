"""Asset lookup that survives any packaging.

Order: files on disk (PyInstaller bundle, next to the exe, source tree, cwd), then the
copy embedded in ``ui/embedded_assets.py`` (generated by tools/embed_assets.py).
So the developer photo, release banners and fonts show up even if a build forgot
to ship the ``assets`` folder.
"""
from __future__ import annotations

import base64
import os
import sys
import zlib

_SRC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def bases() -> list[str]:
    out: list[str] = []
    mp = getattr(sys, "_MEIPASS", None)
    if mp:
        out += [os.path.join(mp, "assets"), mp]
    if getattr(sys, "frozen", False):
        exe = os.path.dirname(sys.executable)
        out += [os.path.join(exe, "assets"), os.path.join(exe, "_internal", "assets"),
                os.path.join(exe, "..", "Resources", "assets")]
    out += [os.path.join(_SRC, "assets"), os.path.join(os.getcwd(), "assets")]
    return out


def find(rel: str) -> str:
    """Path of ``rel`` (e.g. 'developer.png', 'banners/v1.0.png') on disk, or ''."""
    rel = rel.replace("\\", "/")
    for b in bases():
        p = os.path.normpath(os.path.join(b, *rel.split("/")))
        if os.path.isfile(p):
            return p
    return ""


def _embedded() -> dict:
    try:
        from . import embedded_assets
        return embedded_assets.FILES
    except Exception:  # noqa: BLE001
        return {}


def data(rel: str) -> bytes:
    """Raw bytes of an asset ('' -> b'' when it exists nowhere)."""
    rel = rel.replace("\\", "/")
    p = find(rel)
    if p:
        try:
            with open(p, "rb") as fh:
                return fh.read()
        except OSError:
            pass
    blob = _embedded().get(rel)
    if blob:
        try:
            return zlib.decompress(base64.b64decode(blob))
        except Exception:  # noqa: BLE001
            return b""
    return b""


def exists(rel: str) -> bool:
    return bool(find(rel)) or rel.replace("\\", "/") in _embedded()


def pixmap(rel: str):
    """QPixmap for an asset (null pixmap when missing)."""
    from PyQt6.QtGui import QPixmap
    pm = QPixmap()
    p = find(rel)
    if p:
        pm = QPixmap(p)
    if pm.isNull():
        raw = data(rel)
        if raw:
            pm.loadFromData(raw)
    return pm


def changelog_text() -> str:
    raw = data("CHANGELOG.md")
    return raw.decode("utf-8", errors="replace") if raw else ""
