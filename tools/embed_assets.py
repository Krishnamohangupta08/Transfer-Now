"""Embed every runtime asset (developer photo, release banners, fonts, CHANGELOG.md)
into ``ui/embedded_assets.py`` so the built app shows them even if the packager
forgot to copy the data files.  build.py runs this automatically before PyInstaller.

    python tools/embed_assets.py
"""
from __future__ import annotations

import base64
import os
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "assets")
OUT = os.path.join(ROOT, "ui", "embedded_assets.py")


def _collect() -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    for rel in ("developer.png",):
        p = os.path.join(ASSETS, rel)
        if os.path.isfile(p):
            files[rel] = open(p, "rb").read()
    for sub, exts in (("banners", (".png", ".jpg", ".jpeg", ".webp")), ("fonts", (".ttf", ".otf"))):
        d = os.path.join(ASSETS, sub)
        if os.path.isdir(d):
            for n in sorted(os.listdir(d)):
                if n.lower().endswith(exts):
                    files[f"{sub}/{n}"] = open(os.path.join(d, n), "rb").read()
    cl = os.path.join(ROOT, "CHANGELOG.md")
    if os.path.isfile(cl):
        files["CHANGELOG.md"] = open(cl, "rb").read()
    return files


def main() -> int:
    files = _collect()
    lines = ['"""GENERATED by tools/embed_assets.py - do not edit by hand."""', "FILES = {"]
    for rel, data in files.items():
        blob = base64.b64encode(zlib.compress(data, 9)).decode("ascii")
        lines.append(f"    {rel!r}: (")
        for i in range(0, len(blob), 100):
            lines.append(f"        {blob[i:i + 100]!r}")
        lines.append("    ),")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"embedded {len(files)} assets -> {OUT} ({os.path.getsize(OUT) / 1024:.0f} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
